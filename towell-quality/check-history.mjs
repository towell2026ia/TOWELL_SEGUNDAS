import fs from 'node:fs';
import assert from 'node:assert/strict';
import {decode,getMetrics,department,ratio,group,select,modelRates,DEPARTMENTS} from './dist/engine.js';
const load=k=>decode(JSON.parse(fs.readFileSync(`dist/${k}.json`,'utf8')));
const seconds=load('seconds'),production=[...load('costura'),...load('maquila')],crudo=load('crudo'),reference=load('reference');
const m=getMetrics(seconds,production,{period:'2026-09'});
const span=getMetrics(seconds,production,{period:'2026-08..2026-09'}),aug=getMetrics(seconds,production,{period:'2026-08'});
assert.equal(span.total,aug.total+m.total);assert.equal(span.den,aug.den+m.den);
assert.ok(span.rows.every(r=>r[0]>='2026-08-01'&&r[0]<'2026-10-01'));
assert.equal(getMetrics(seconds,production,{period:'2026-09..2026-09'}).total,m.total);
assert.equal(m.total,26686);assert.equal(m.den,1000316);assert.ok(Math.abs(m.rate-2.667756988791542)<1e-12);
assert.equal(DEPARTMENTS.reduce((n,d)=>n+m.byDepartment[d],0),m.total);
assert.deepEqual(m.byDepartment,{TEJIDO:16786,'TINTORERÍA':5485,COSTURA:4415,'SIN CLASIFICAR':0});
assert.ok(seconds.slice(0,36965).every(r=>department(r)!=='SIN CLASIFICAR'));
assert.equal(department(['','','','','Oalla con Plano/Sin Rizo/Sin Plano de corte']),'TEJIDO');
assert.equal(department(['','','','','Mancha de Oxido']),'TEJIDO');
assert.equal(department(['','','','','Rota Tintoreria']),'TINTORERÍA');
assert.equal(department(['','','','','Subida a Rizo Costura Longitudinal']),'COSTURA');
assert.ok(seconds.length>=36965);assert.ok(production.length>=28832);assert.ok(crudo.length>=92077);
const key=r=>JSON.stringify(r.slice(0,4));
assert.deepEqual(new Map(group(select(production,{period:'2026-09'}),key)),new Map(group(reference,key)));
const g=getMetrics(seconds,production,{period:'2026-09',model:'GRANADA SORH II'});
assert.equal(g.den,60249);assert.equal(g.total,2287);
const rayas=getMetrics(seconds,production,{period:'2026-09',model:'GRANADA SORH II',defect:'Rayas'});
assert.equal(rayas.den,g.den);assert.equal(rayas.total,566);
assert.equal(getMetrics(seconds,production,{period:'2026-09',model:'NO EXISTE'}).rate,null);
assert.equal(ratio(2,0),null);
assert.ok(select(seconds,{period:'2026-09',department:'TEJIDO'}).every(r=>department(r)==='TEJIDO'));
const c=getMetrics(seconds.slice(0,36965),[],{period:'all'});assert.equal(c.total,176476);assert.equal(c.rate,null);
assert.ok(Math.abs(crudo.slice(0,92077).reduce((n,r)=>n+r[5],0)-611651.78)<1e-6);
assert.ok(select(seconds,{period:'2026-09',color:'__missing__'}).every(r=>r[3]===''));
console.log(JSON.stringify({status:'PASS',september:m.rate,production:m.den,seconds:m.total,granada:g.rate,department_totals:m.byDepartment,source_dimension_groups:'exact match',checks:'historical totals, cohort filters, missing denominator, unknown catalogue, source rows and crudo separation'}));
